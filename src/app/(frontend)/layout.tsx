import type { Metadata } from "next";
import { Urbanist } from "next/font/google";
import { satoshi, cabinet } from "@/lib/fonts";
import "./globals.css";
import "aos/dist/aos.css";
import Footer from "@/components/ui/footer";
import Navbar from "@/components/ui/navbar";
import LocomotiveScrollWrapper from "@/lib/LocomotiveScroll";
import StartAOS from "@/lib/StartAos";
import JellyBlobCursor from "@/components/ui/cursor";
import { payload } from "@/lib/utils";

const UrbanistSans = Urbanist({
  variable: "--font-urbanist",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  metadataBase: new URL("http://localhost:3000"),
  title: "Shreepech Internationals",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const navbarData = await payload.findGlobal({
    slug: "navbar",
  });

  const footerData = await payload.findGlobal({
    slug: "footer",
  });

  return (
    <html lang="en">
      <body
        id="shreepech-smooth"
        className={`${UrbanistSans.variable} ${satoshi.variable} ${cabinet.variable} font-satoshi antialiased`}
      >
        <Navbar data={navbarData} />
        <JellyBlobCursor />
        <LocomotiveScrollWrapper />
        <StartAOS />
        <main className="mx-auto min-h-screen w-full">{children}</main>
        <Footer data={footerData} />
      </body>
    </html>
  );
}
